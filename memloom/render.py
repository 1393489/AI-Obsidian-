"""Markdown rendering: sessions, projects, topics, index.

Two rules shape every page here:

1. **Nothing is invented.** There is no LLM in v0.1, so a session page shows what the
   user actually asked plus real excerpts and tool stats. No polished prose summary that
   might be wrong — a page you can trust beats a page that reads nicely.
2. **Generated files are marked and safe to refresh.** Every page ends with a
   ``generated by memloom`` comment; the writer only prunes files carrying that mark, so
   your hand-written notes in the vault are never deleted.
"""

from __future__ import annotations

import os
from collections import Counter, defaultdict
from typing import Dict, List, Optional, Tuple

from . import __version__
from .group import Project, SessionFacts, Topic
from .util import clip_text, ensure_dir, fmt_dt, safe_name, short_id, slug, to_local

GENERATED_MARK = "<!-- generated by memloom"
INDEX_NAME = "00-总索引"
GUIDE_NAME = "99-使用说明"
DIR_PROJECT = "10-项目"
DIR_SESSION = "20-会话"
DIR_TOPIC = "30-主题"
DIR_ARCHIVE = "90-原文归档"

_CATEGORY_ORDER = ("踩坑", "代码", "工具")


# ------------------------------------------------------------------ helpers

def _dt(session) -> str:
    return fmt_dt(to_local(session.started_at)) if getattr(session, "started_at", None) else "时间未知"


def _range(session) -> str:
    s, e = getattr(session, "started_at", None), getattr(session, "ended_at", None)
    if not s:
        return "时间未知"
    a = fmt_dt(to_local(s), "%Y-%m-%d %H:%M")
    if not e or e == s:
        return a
    b = fmt_dt(to_local(e), "%Y-%m-%d %H:%M")
    return f"{a} → {b}"


def _link(name: str) -> str:
    """Obsidian wikilink to a page by its file base name."""
    return f"[[{name}]]"


def _neutralize_links(text: str) -> str:
    """Stop quoted conversation text from becoming a wikilink.

    People talk *about* wikilinks (and this very README mentions ``[[双链]]``), so a
    session body can contain ``[[名字]]`` that was never meant as a link. Obsidian
    happily renders it as one and reports it as a broken link to a page that will
    never exist. Escaping only the opening bracket keeps the text readable while
    making it inert.
    """
    return (text or "").replace("[[", "\\[[")


def session_page_name(session) -> str:
    date = to_local(session.started_at).strftime("%Y-%m-%d") if session.started_at else "0000-00-00"
    # 32, not 24: at 24 a title carrying the 「· 01」 run number was cut mid-number
    # (``…-douyin_comments-0``), so every numbered run collided again.
    title = slug(session.title or "untitled", 32)
    return f"{date}-{short_id(session.id, 8)}-{title}"


def topic_page_name(topic: Topic) -> str:
    # 48 chars keeps two different failures that share a long prefix from colliding on the
    # same file name (a collision costs a ``-1a2b`` suffix, which reads like noise).
    return f"{topic.category}-{safe_name(_pretty(topic.title), 48)}"


#: fingerprints keep volatile parts as ``<path>``/``<uuid>`` markers; on a page they read
#: better as an ellipsis (and safe_name would otherwise strip the angle brackets).
_MARKERS = (("<path>", "…"), ("<uuid>", "…"), ("<ts>", "…"), ("<n>", "N"))


def _pretty(title: str) -> str:
    s = title or ""
    for a, b in _MARKERS:
        s = s.replace(a, b)
    return s


def _front_matter(kind: str, source: str, tag_prefix: str, extra: Optional[List[str]] = None) -> str:
    lines = ["---", f"类型: {kind}"]
    for e in extra or []:
        if e:
            lines.append(e)
    lines.append(f"来源: {source}")
    lines.append("tags:")
    lines.append(f"  - {tag_prefix}/{kind}")
    lines.append("---")
    lines.append("")
    return "\n".join(lines)


def _ordered_sessions(sessions: Dict[str, object], ids: List[str]) -> List[object]:
    def key(sid: str):
        s = sessions.get(sid)
        return getattr(s, "started_at", None) or _EPOCH

    known = [sid for sid in ids if sid in sessions]
    return [sessions[sid] for sid in sorted(known, key=key, reverse=True)]


import datetime as _dtmod

_EPOCH = _dtmod.datetime(1970, 1, 1, tzinfo=_dtmod.timezone.utc)


# ------------------------------------------------------------------ session page

def render_session(session, facts: Optional[SessionFacts], project: Optional[Project],
                   topics: List[Topic], source_label: str, tag_prefix: str,
                   prompt_cap: int = 900, reply_cap: int = 600) -> str:
    out: List[str] = []
    out.append(
        _front_matter(
            "会话记录",
            source_label,
            tag_prefix,
            [
                f"会话ID: {session.id}",
                f"日期: {to_local(session.started_at).strftime('%Y-%m-%d') if session.started_at else '未知'}",
                f"时间范围: {_range(session)}",
                f"轮次: {len(session.turns)}",
                f"工具调用: {session.n_tools}",
                f"模型: {session.model or '未知'}",
                f"工作目录: {session.cwd or '未知'}",
            ],
        )
    )
    out.append(f"# {session.title or '(无标题)'}")
    out.append("")
    out.append(f"← 返回 {_link(INDEX_NAME)}")
    out.append("")
    meta = session.meta or {}
    bits = []
    if meta.get("agentPreset"):
        bits.append(f"预设 `{meta['agentPreset']}`")
    if meta.get("version"):
        bits.append(f"版本 `{meta['version']}`")
    if session.cost_usd:
        bits.append(f"花费 ${session.cost_usd:.2f}")
    if bits:
        out.append("> " + " · ".join(bits))
        out.append("")

    if project:
        out.append(f"**项目**：{_link(project.name)}")
        out.append("")

    if topics:
        out.append("**相关主题**：" + " · ".join(_link(topic_page_name(t)) for t in topics))
        out.append("")

    # -- what the user asked (this is the honest substitute for an LLM summary)
    prompts = [t.prompt.strip() for t in session.turns if (t.prompt or "").strip()]
    if prompts:
        out.append("## 用户请求一览")
        out.append("")
        for i, p in enumerate(prompts, 1):
            one = _neutralize_links(" ".join(p.split())[:120])
            out.append(f"{i}. {one}")
        out.append("")

    if session.tool_histogram:
        out.append("## 工具用量")
        out.append("")
        out.append("| 工具 | 次数 |")
        out.append("|---|---|")
        for name, n in Counter(session.tool_histogram).most_common(20):
            out.append(f"| `{name}` | {n} |")
        out.append("")

    if facts and facts.paths:
        out.append("## 涉及文件")
        out.append("")
        for p, n in facts.paths.most_common(25):
            out.append(f"- `{p}`" + (f" ×{n}" if n > 1 else ""))
        out.append("")

    if facts and facts.commands:
        heads = [(h.replace("tool:", ""), n) for h, n in facts.commands.most_common(12)]
        out.append("## 常用命令")
        out.append("")
        out.append(" · ".join(f"`{h}`×{n}" for h, n in heads))
        out.append("")

    errs = [e for e in (session.errors or []) if e]
    if not errs and facts:
        errs = [s for _fp, s in facts.errors[:8]]
    if errs:
        out.append("## 报错")
        out.append("")
        for e in errs[:10]:
            out.append("```")
            out.append(clip_text(e.strip(), 400))
            out.append("```")
        out.append("")

    out.append("## 逐轮记录")
    out.append("")
    for i, t in enumerate(session.turns, 1):
        head = f"### {i}. {fmt_dt(to_local(t.at), '%m-%d %H:%M') if t.at else '时间未知'}"
        out.append(head)
        out.append("")
        if (t.prompt or "").strip():
            out.append("**用户**：")
            out.append("")
            out.append(_neutralize_links(clip_text(t.prompt.strip(), prompt_cap)))
            out.append("")
        if (t.reply or "").strip():
            out.append("**助手**：")
            out.append("")
            out.append(_neutralize_links(clip_text(t.reply.strip(), reply_cap)))
            out.append("")
        if t.tools:
            names = Counter(x.name for x in t.tools)
            fails = [x for x in t.tools if x.ok is False]
            line = "工具：" + " · ".join(f"`{n}`×{c}" for n, c in names.most_common())
            if fails:
                line += f"（其中 {len(fails)} 次失败）"
            out.append(line)
            out.append("")
            for x in fails[:5]:
                if x.error:
                    out.append(f"- `{x.name}` → {clip_text(' '.join(x.error.split()), 200)}")
            if fails:
                out.append("")

    out.append("")
    out.append(f"**原始存档**：`{session.source or '未记录'}`")
    out.append("")
    out.append(_mark())
    return "\n".join(out)


def _mark() -> str:
    return f"{GENERATED_MARK} v{__version__} — edits will be overwritten on the next build. -->"


# ------------------------------------------------------------------ project page

def render_project(project: Project, sessions: Dict[str, object], factsmap: Dict[str, SessionFacts],
                   topics: List[Topic], source_label: str, tag_prefix: str) -> str:
    ordered = _ordered_sessions(sessions, project.sessions)
    out: List[str] = []
    out.append(
        _front_matter(
            "项目",
            source_label,
            tag_prefix,
            [f"会话数: {project.n_sessions}", f"工作目录: {', '.join(project.cwds) if project.cwds else '未标注'}"],
        )
    )
    out.append(f"# {project.name}")
    out.append("")
    out.append(f"← 返回 {_link(INDEX_NAME)}")
    out.append("")
    if project.cwds:
        out.append("> 工作目录：" + " · ".join(f"`{c}`" for c in project.cwds))
        out.append("")

    if ordered:
        first = to_local(ordered[-1].started_at) if ordered[-1].started_at else None
        last = to_local(ordered[0].started_at) if ordered[0].started_at else None
        span = f"{fmt_dt(first, '%Y-%m-%d')} → {fmt_dt(last, '%Y-%m-%d')}" if first and last else "未知"
        tools = sum(s.n_tools for s in ordered)
        out.append(f"**{project.n_sessions} 个会话**，跨度 {span}，累计 {tools} 次工具调用。")
        out.append("")

    out.append("## 会话")
    out.append("")
    out.append("| 日期 | 会话 | 轮次 | 工具 | 报错 |")
    out.append("|---|---|---|---|---|")
    for s in ordered:
        f = factsmap.get(s.id)
        nerr = len(s.errors or []) + (len(f.errors) if f else 0)
        out.append(
            f"| {fmt_dt(to_local(s.started_at), '%m-%d') if s.started_at else '—'} "
            f"| {_link(session_page_name(s))} | {len(s.turns)} | {s.n_tools} | {nerr or '—'} |"
        )
    out.append("")

    if project.paths:
        out.append("## 主要文件")
        out.append("")
        for p, n in project.paths.most_common(30):
            out.append(f"- `{p}`" + (f" ×{n}" if n > 1 else ""))
        out.append("")

    if project.components:
        out.append("## 热点区域")
        out.append("")
        out.append(" · ".join(f"`{c}`×{n}" for c, n in project.components.most_common(20)))
        out.append("")

    if topics:
        out.append("## 相关主题")
        out.append("")
        out.append(" · ".join(_link(topic_page_name(t)) for t in topics))
        out.append("")

    if project.errors:
        out.append("## 反复出现的问题")
        out.append("")
        for fp, n in project.errors.most_common(10):
            out.append(f"- {clip_text(fp, 160)}（{n} 个会话）")
        out.append("")

    out.append("")
    out.append(_mark())
    return "\n".join(out)


# ------------------------------------------------------------------ topic page

def render_topic(topic: Topic, sessions: Dict[str, object], source_label: str, tag_prefix: str) -> str:
    out: List[str] = []
    out.append(_front_matter("主题", source_label, tag_prefix, [f"分类: {topic.category}", f"会话数: {len(topic.sessions)}"]))
    out.append(f"# {_pretty(topic.title)}")
    out.append("")
    out.append(f"← 返回 {_link(INDEX_NAME)}")
    out.append("")
    out.append(f"出现在 **{len(topic.sessions)} 个会话**里。")
    out.append("")

    ordered = _ordered_sessions(sessions, topic.sessions)
    if ordered:
        out.append("## 相关会话")
        out.append("")
        for s in ordered:
            out.append(f"- {_link(session_page_name(s))} — {fmt_dt(to_local(s.started_at), '%Y-%m-%d') if s.started_at else '时间未知'}")
        out.append("")

    if topic.evidence:
        out.append("## 原文证据")
        out.append("")
        for e in topic.evidence[:8]:
            if not e:
                continue
            out.append("```")
            out.append(clip_text(e.strip(), 500))
            out.append("```")
        out.append("")

    out.append(_mark())
    return "\n".join(out)


# ------------------------------------------------------------------ index

def render_index(sessions: Dict[str, object], projects: List[Project], topics: List[Topic],
                 source_label: str, tag_prefix: str, title: str) -> str:
    ordered = _ordered_sessions(sessions, list(sessions.keys()))
    out: List[str] = []
    out.append(_front_matter("索引", source_label, tag_prefix, [f"会话数: {len(sessions)}", f"项目数: {len(projects)}", f"主题数: {len(topics)}"]))
    out.append(f"# {INDEX_NAME} · {title}")
    out.append("")
    out.append(
        f"共收录 **{len(sessions)} 个会话**、**{len(projects)} 个项目页**、**{len(topics)} 个主题页**。"
        "开工前先读本页，再打开项目页，不要翻全库。"
    )
    out.append("")
    out.append(f"- 怎么用：{_link(GUIDE_NAME)}")
    out.append("")

    out.append("## 一、项目地图")
    out.append("")
    out.append("| 项目 | 会话数 | 最近活跃 | 累计工具 |")
    out.append("|---|---|---|---|")
    for p in projects:
        ps = [sessions[sid] for sid in p.sessions if sid in sessions]
        last = max((s.started_at for s in ps if s.started_at), default=None)
        tools = sum(s.n_tools for s in ps)
        out.append(
            f"| {_link(p.name)} | {p.n_sessions} | {fmt_dt(to_local(last), '%Y-%m-%d') if last else '—'} | {tools} |"
        )
    out.append("")

    if topics:
        out.append("## 二、主题分类")
        out.append("")
        groups: Dict[str, List[Topic]] = defaultdict(list)
        for t in topics:
            groups[t.category].append(t)
        for cat in _CATEGORY_ORDER:
            items = groups.get(cat)
            if not items:
                continue
            out.append(f"**{cat}**（{len(items)}）")
            out.append("")
            out.append(" · ".join(_link(topic_page_name(t)) for t in items))
            out.append("")
        for cat, items in groups.items():
            if cat in _CATEGORY_ORDER:
                continue
            out.append(f"**{cat}**（{len(items)}）")
            out.append("")
            out.append(" · ".join(_link(topic_page_name(t)) for t in items))
            out.append("")

    out.append("## 三、会话时间线（最近 40 条）")
    out.append("")
    proj_of = {}
    for p in projects:
        for sid in p.sessions:
            proj_of[sid] = p.name
    for s in ordered[:40]:
        date = fmt_dt(to_local(s.started_at), "%Y-%m-%d") if s.started_at else "时间未知"
        proj = proj_of.get(s.id)
        tail = f" · {_link(proj)}" if proj else ""
        out.append(f"- {date} {_link(session_page_name(s))}{tail}")
    out.append("")
    if len(ordered) > 40:
        out.append(f"（更早的 {len(ordered) - 40} 条见各项目页）")
        out.append("")

    out.append("## 四、统计")
    out.append("")
    tools = Counter()
    models = Counter()
    for s in ordered:
        tools.update(s.tool_histogram or {})
        if s.model:
            models[s.model] += 1
    total_tools = sum(tools.values())
    out.append(f"- 工具调用合计 **{total_tools}** 次，涉及 **{len(tools)}** 种工具")
    if tools:
        out.append("- 用量前五：" + " · ".join(f"`{n}` {c}" for n, c in tools.most_common(5)))
    if models:
        out.append("- 模型：" + " · ".join(f"`{m}` {c} 个会话" for m, c in models.most_common(5)))
    out.append("")
    out.append(_mark())
    return "\n".join(out)


# ------------------------------------------------------------------ guide

def render_guide(title: str, source_label: str, tag_prefix: str, session_roots: List[Tuple[str, str]]) -> str:
    out: List[str] = []
    out.append(_front_matter("使用说明", source_label, tag_prefix))
    out.append(f"# 怎么用这个库")
    out.append("")
    out.append(f"← 返回 {_link(INDEX_NAME)}")
    out.append("")
    out.append("## 三个入口")
    out.append("")
    out.append(f"1. **{_link(INDEX_NAME)}** —— 项目地图 + 主题分类 + 时间线，开工第一站。")
    out.append(f"2. **{DIR_PROJECT}/** —— 每个工作目录一篇，列出该目录下所有会话、主要文件、反复出现的问题。")
    out.append(f"3. **{DIR_TOPIC}/** —— 跨会话复现的报错与热点区域，踩坑前先搜这里。")
    out.append("")
    out.append("## 页面里字段的含义")
    out.append("")
    out.append("| 字段 | 含义 |")
    out.append("|---|---|")
    out.append("| 会话ID | 采集器给的稳定标识，用于对回原始存档 |")
    out.append("| 轮次 | 一次「用户发问 → 助手干活」 |")
    out.append("| 工具调用 | 会话里所有工具执行次数（含失败） |")
    out.append("| 报错 | 工具返回 is_error 或文本里匹配到错误样式的行 |")
    out.append("")
    out.append("## 内容从哪来")
    out.append("")
    out.append("本库由 `memloom` 从本机 AI 编码会话存档生成，**不使用大模型**：")
    out.append("页面上的请求、命令、报错、文件路径都是从原文里抽出来的真实内容，")
    out.append("所以不会有「看起来通顺但编的」摘要，反过来也不会替你想出漂亮的主题名。")
    out.append("")
    if session_roots:
        out.append("## 数据来源")
        out.append("")
        for name, root in session_roots:
            out.append(f"- `{name}` → `{root}`")
        out.append("")
    out.append("## 重新生成")
    out.append("")
    out.append("```bash")
    out.append("memloom build --out <本库路径>")
    out.append("```")
    out.append("")
    out.append("带 `generated by memloom` 标记的文件会被覆盖；你自己加的笔记不会被删除。")
    out.append("")
    out.append(_mark())
    return "\n".join(out)


def render_archive_note(source_label: str, tag_prefix: str, sessions: Dict[str, object]) -> str:
    out: List[str] = []
    out.append(_front_matter("说明", source_label, tag_prefix))
    out.append("# 原文归档")
    out.append("")
    out.append(f"← 返回 {_link(INDEX_NAME)}")
    out.append("")
    out.append("原始会话文件留在采集位置，没有复制进本库（会话存档动辄几十上百 MB，")
    out.append("复制一份既占空间又会过时）。每个会话页底部都写了它的原始路径，需要原文时直接打开那一个。")
    out.append("")
    rows = [(sid, s) for sid, s in sessions.items() if getattr(s, "source", None)]
    if rows:
        out.append("| 会话 | 原始文件 |")
        out.append("|---|---|")
        for _sid, s in rows[:200]:
            out.append(f"| {_link(session_page_name(s))} | `{s.source}` |")
        out.append("")
    out.append(_mark())
    return "\n".join(out)
